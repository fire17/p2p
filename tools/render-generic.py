#!/usr/bin/env python3
"""Render the GENERIC Windows join script (join.ps1) - key as a parameter, never a per-key file.
join.sh is maintained by hand (same helper: tools/join-client.mjs is synced FROM join.sh's embedded copy).
join.ps1 is written as pure ASCII: Windows PowerShell 5.1 decodes BOM-less scripts and charset-less HTTP
bodies as ANSI/Latin-1, so the helper's non-ASCII characters (all inside JS string literals) become \\uXXXX
escapes - identical strings at runtime. test/ps1-encoding.ps1 enforces ASCII for every *.ps1."""
import re, pathlib
here = pathlib.Path(__file__).resolve().parent; root = here.parent
tpl = (here / 'join-bootstrap.ps1.in').read_text()
rj = (here / 'render-join.mjs').read_text()
m = re.search(r"ps1: \{ url: (\w+) \+ '([^']+)', sha256: '([a-f0-9]{64})'", rj)
ps1_base = re.search(r"const " + m.group(1) + r" = '([^']+)'", rj).group(1)
helper = (here / 'join-client.mjs').read_text().rstrip()
assert all(ord(c) <= 0xFFFF for c in helper), "a \\uXXXX escape covers BMP characters only"
helper = ''.join(c if ord(c) < 128 else '\\u%04x' % ord(c) for c in helper)
assert "\n'@" not in helper, "helper would terminate the PowerShell here-string"
# The key reaches the script in one of two ways - both user-typed, neither a file on this site:
#   $env:P2P_KEY='<LISTENER_KEY>'; irm https://p2p.akeyo.io/join.ps1 | iex      (the line we hand out)
#   & ([scriptblock]::Create((irm https://p2p.akeyo.io/join.ps1))) <LISTENER_KEY>    (older line, still works)
# `| iex` runs in the CALLER's scope, so the script must assign nothing at top level: no top-level param()
# (it would reset a caller's $Key/$KEY - case-insensitive - or fail with "variable has been optimized"
# inside a function). The key is a param of the inner `& { }` block, fed by `@args`: the old line's
# argument arrives there, while iex always invokes with empty $args (never the caller's).
USAGE = "$env:P2P_KEY='<LISTENER_KEY>'; irm https://p2p.akeyo.io/join.ps1 | iex"
OPEN, CLOSE = "& {\n", "\n}\n"
assert tpl.count(OPEN) == 1 and '\n' + OPEN in tpl and tpl.endswith(CLOSE), 'template must be ONE top-level & { } block'
s = tpl.replace("# Generated by tools/render-join.mjs. PowerShell 5.1 and 7.\n# Installs verified Bun + p2p, joins chat, and never enables terminal access.\n",
"""# p2p.akeyo.io/join.ps1 - ONE static script for every Windows machine; the listener key is typed by the user, never a file on this site:
#   """ + USAGE + """
# (share it as https://p2p.akeyo.io/#/join/<LISTENER_KEY> - the page renders this line client-side)
# The older form still works: & ([scriptblock]::Create((irm https://p2p.akeyo.io/join.ps1))) <LISTENER_KEY>
# Installs verified Bun + p2p v0.3.8, joins the listener's chat, identifies the machine. Never enables terminal access.
# Rendered from tools/join-bootstrap.ps1.in + tools/join-client.mjs by tools/render-generic.py. PowerShell 5.1 and 7.
""")
s = s.replace(OPEN, OPEN + "  param([string]$Key = '')\n", 1)
s = s[:-len(CLOSE)] + "\n} @args\n"
# An explicit argument wins; the env var is read once and cleared before anything else runs (no child inherits it).
s = s.replace("  $joinKey = '@@KEY@@'\n",
  "  $joinKey = $Key\n"
  "  if (-not $joinKey) { $joinKey = [Environment]::GetEnvironmentVariable('P2P_KEY', 'Process') }\n"
  "  [Environment]::SetEnvironmentVariable('P2P_KEY', $null, 'Process')\n"
  "  if (-not $joinKey) { throw 'usage: " + USAGE.replace("'", "''") + "' }\n")
s = s.replace('@@INSTALLER_URL@@', ps1_base + m.group(2)).replace('@@INSTALLER_SHA256@@', m.group(3)).replace('@@HELPER@@', helper)
assert '@@' not in s
assert s.isascii(), 'join.ps1 must be pure ASCII (Windows PowerShell 5.1 reads it as ANSI)'
import sys
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'join.ps1'  # an explicit path lets the test check freshness
out.write_text(s, encoding='utf-8')
print(out.name, 'rendered', len(s), 'bytes')
